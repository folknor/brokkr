#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use std::path::{Path, PathBuf};

use super::{describe, listing};
use crate::pbfhogg::binary::LibraryHarness;

const DOC: &str = r#"{"protocol": 1, "scenarios": [
  {"id": "repeat-cat", "description": "cat the input twice in a row", "deadline_s": 600,
   "roles": [
     {"id": "input", "kind": "pbf", "source": "dataset", "variant": "indexed"},
     {"id": "out-a", "kind": "pbf", "source": "output", "owner": "a"},
     {"id": "seed", "kind": "directory", "source": "generated"},
     {"id": "tmp-a", "kind": "directory", "source": "scratch", "owner": "a"}
   ],
   "calls": [{"id": "a", "label": "cat input -> out-a", "stream": ["counters.v1"]}],
   "assertions": [{"id": "a.outcome", "call": "a"}, {"id": "whole", "call": null}]}
]}"#;

/// Install `body` as an executable shell script under a fresh scratch root.
fn harness(name: &str, body: &str) -> (PathBuf, PathBuf) {
    use std::os::unix::fs::PermissionsExt;
    let root = crate::test_scratch::scratch("pbfhogg-library", name);
    let path = root.join("harness");
    let staged = root.join("harness.new");
    std::fs::write(&staged, format!("#!/bin/sh\n{body}\n")).unwrap();
    std::fs::set_permissions(&staged, std::fs::Permissions::from_mode(0o755)).unwrap();
    std::fs::rename(&staged, &path).unwrap();
    (root, path)
}

/// A script that answers `--describe-harness` with `doc` and fails anything else.
fn describing(doc: &str) -> String {
    format!("[ \"$*\" = \"--describe-harness\" ] || exit 9\ncat <<'EOF'\n{doc}\nEOF")
}

fn describe_with(root: &Path, path: &Path, limit: usize) -> Result<Vec<u8>, String> {
    let handle = LibraryHarness::fixture(path, root).map_err(|e| e.to_string())?;
    handle.describe(limit).map_err(|e| e.to_string())
}

#[test]
fn a_harness_lists_the_scenarios_it_describes() {
    let (root, path) = harness("lists", &describing(DOC));
    let bytes = describe_with(&root, &path, describe::DESCRIBE_LIMIT).unwrap();
    let doc = describe::parse(&bytes).unwrap();
    let lines = listing(&doc);
    assert_eq!(lines[0], "repeat-cat  1 call, deadline 600s");
    assert_eq!(lines[1], "  cat the input twice in a row");
    assert!(
        lines.iter().any(|l| l.contains("call       a")
            && l.ends_with("cat input -> out-a (stream: counters.v1)"))
    );
    assert!(
        lines
            .iter()
            .any(|l| l.contains("input") && l.ends_with("pbf dataset, variant indexed"))
    );
    assert!(
        lines
            .iter()
            .any(|l| l.contains("out-a") && l.ends_with("pbf output of a"))
    );
    assert!(
        lines
            .iter()
            .any(|l| l.contains("seed") && l.ends_with("directory generated by setup"))
    );
    assert!(
        lines
            .iter()
            .any(|l| l.contains("tmp-a") && l.ends_with("directory scratch of a"))
    );
    assert!(
        lines
            .iter()
            .any(|l| l.contains("a.outcome") && l.ends_with("call a"))
    );
    assert!(
        lines
            .iter()
            .any(|l| l.contains("whole") && l.ends_with("scenario"))
    );
}

#[test]
fn a_describe_run_that_fails_or_speaks_on_stderr_is_refused() {
    let (root, path) = harness("exit", "echo broken >&2\nexit 3");
    let e = describe_with(&root, &path, 1024).unwrap_err();
    assert!(e.contains("exited 3, not 0: broken"), "{e}");

    let (root, path) = harness("stderr", &format!("{}\necho noise >&2", describing(DOC)));
    let e = describe_with(&root, &path, describe::DESCRIBE_LIMIT).unwrap_err();
    assert!(e.contains("wrote to stderr") && e.contains("noise"), "{e}");

    let (root, path) = harness("signal", "kill -9 $$");
    let e = describe_with(&root, &path, 1024).unwrap_err();
    assert!(e.contains("killed by signal 9"), "{e}");
}

#[test]
fn a_describe_document_past_the_limit_is_refused_not_truncated() {
    let (root, path) = harness("over", &describing(DOC));
    let e = describe_with(&root, &path, 64).unwrap_err();
    assert!(e.contains("more than the 64-byte limit"), "{e}");
}

#[test]
fn a_document_of_exactly_the_limit_passes_and_one_byte_more_does_not() {
    let (root, path) = harness("exact", &describing(DOC));
    // The heredoc ends the document with a newline.
    let size = DOC.len() + 1;
    assert_eq!(describe_with(&root, &path, size).unwrap().len(), size);
    let e = describe_with(&root, &path, size - 1).unwrap_err();
    assert!(e.contains("more than the"), "{e}");
}

#[test]
fn a_replaced_harness_is_refused_under_a_live_handle() {
    let (root, path) = harness("replaced", &describing(DOC));
    let handle = LibraryHarness::fixture(&path, &root).unwrap();
    let (_, other) = harness("replacement", &describing(DOC));
    std::fs::rename(&other, &path).unwrap();
    let e = handle
        .describe(describe::DESCRIBE_LIMIT)
        .unwrap_err()
        .to_string();
    assert!(e.contains("was replaced under a live handle"), "{e}");
}
